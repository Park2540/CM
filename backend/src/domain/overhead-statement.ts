// ---------- ตรวจและทำความสะอาดข้อมูล ----------

const LIMIT = { sections: 30, subsections: 40, blocks: 30, items: 60, rows: 60, text: 3000, title: 300 };
const clean = (value: unknown, max: number) => (typeof value === 'string' ? value.replace(/\r\n/g, '\n').trim().slice(0, max) : '');
const cleanId = (value: unknown, prefix: string) => (typeof value === 'string' && /^[\w-]{1,40}$/.test(value) ? value : id(prefix));
const STYLES = new Set(['number', 'bullet', 'clause']);

function cleanBlocks(raw: unknown): Block[] {
    if (!Array.isArray(raw)) return [];
    return raw.slice(0, LIMIT.blocks).flatMap((input): Block[] => {
        const b = (input ?? {}) as Partial<Block>;
        const blockId = cleanId(b.id, 'b');
        if (b.kind === 'paragraph') {
            const text = clean(b.text, LIMIT.text);
            return text ? [{ id: blockId, kind: 'paragraph', text }] : [];
        }
        if (b.kind === 'list') {
            const items = (Array.isArray(b.items) ? b.items : []).map((item) => clean(item, LIMIT.text)).filter(Boolean).slice(0, LIMIT.items);
            const title = clean(b.title, LIMIT.title);
            return items.length ? [{ id: blockId, kind: 'list', style: STYLES.has(String(b.style)) ? b.style : 'number', ...(title ? { title } : {}), items }] : [];
        }
        if (b.kind === 'responsibility') {
            const rows = (Array.isArray(b.rows) ? b.rows : []).slice(0, LIMIT.rows).flatMap((rawRow): Row[] => {
                const r = (rawRow ?? {}) as Partial<Row>;
                const item = clean(r.item, LIMIT.title);
                const note = clean(r.note, LIMIT.title);
                return item ? [{ id: cleanId(r.id, 'r'), item, contractor: r.contractor === true, owner: r.owner === true, ...(note ? { note } : {}) }] : [];
            });
            return [{ id: blockId, kind: 'responsibility', rows }];
        }
        return [];
    });
}

/** ข้อมูลจากหน้าจอ → เอกสารที่บันทึกได้ (ตัดช่องว่าง/ข้อความยาวเกิน ไม่ทิ้งหัวข้อที่ยังไม่มีเนื้อหา) */
export function normalizeStatement(raw: unknown): Statement | { error: string } {
    const input = (raw ?? {}) as Partial<Statement>;
    const title = clean(input.title, LIMIT.title);
    if (!title) return { error: 'กรุณาระบุชื่อเอกสารชี้แจงค่าดำเนินการ' };
    const sections = (Array.isArray(input.sections) ? input.sections : []).slice(0, LIMIT.sections).map(
        (s): Section => ({
            id: cleanId(s?.id, 's'),
            title: clean(s?.title, LIMIT.title) || 'หัวข้อใหม่',
            blocks: cleanBlocks(s?.blocks),
            subsections: (Array.isArray(s?.subsections) ? s.subsections : []).slice(0, LIMIT.subsections).map((ss) => ({ id: cleanId(ss?.id, 's'), title: clean(ss?.title, LIMIT.title) || 'หัวข้อย่อยใหม่', blocks: cleanBlocks(ss?.blocks) }))
        })
    );
    const subtitle = clean(input.subtitle, LIMIT.title);
    return { title, ...(subtitle ? { subtitle } : {}), sections };
}

// ---------- แม่แบบของบริษัท ----------

export const statementTemplate: Statement = defaultStatement();
persistObject('overhead_statement_template', statementTemplate);

export const copyStatement = (statement: Statement = statementTemplate): Statement => structuredClone({ title: statement.title, ...(statement.subtitle ? { subtitle: statement.subtitle } : {}), sections: statement.sections });

export function saveStatementTemplate(raw: unknown): { ok: Statement } | { error: string } {
    const result = normalizeStatement(raw);
    if ('error' in result) return result;
    delete statementTemplate.subtitle;
    Object.assign(statementTemplate, result);
    return { ok: copyStatement() };
}

/** คืนแม่แบบเป็นค่าตั้งต้นของระบบ */
export function resetStatementTemplate(): Statement {
    delete statementTemplate.subtitle;
    Object.assign(statementTemplate, defaultStatement());
    return copyStatement();
}
