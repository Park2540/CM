/** ตัวเลือกจากหน้า "ตั้งค่างานก่อสร้าง" (key → ค่า ตาม GET /settings/construction-options) */
export type SetupOptions = Record<string, string | boolean | string[]>;

/**
 * เงื่อนไขที่งานจะถูกรวมในแผน: ทุก key ต้องตรง — ไม่มี when = ใช้กับทุกโครงการ
 * - ตัวเลือกแบบเลือกได้ 1 ค่า: ค่าที่เลือกต้องอยู่ในรายการ เช่น `{ foundation: ['driven', 'bored'] }`
 * - ตัวเลือกแบบเลือกได้หลายค่า: เลือกค่าใดค่าหนึ่งในรายการ เช่น `{ systems: ['lift'] }`
 * - ตัวเลือกใช่/ไม่ใช่: `{ pileLoadTest: ['true'] }`
 */
export type TaskCondition = Record<string, string[]>;

export interface PlanTaskTemplate {
    code: string;
    name: string;
    team: string;
    start: string;
    end: string;
    note?: string;
    when?: TaskCondition;
}

export function includesTask(task: PlanTaskTemplate, options: SetupOptions): boolean {
    return Object.entries(task.when ?? {}).every(([key, allowed]) => {
        const value = options[key];
        // งาน "ชั้น 2" = งานชั้นบน ใช้กับอาคาร 2 ชั้นขึ้นไป (สร้างซ้ำทีละชั้นใน timeline-generator)
        if (key === 'floors' && allowed.includes('2') && Number(value) >= 2) return true;
        return Array.isArray(value) ? value.some((item) => allowed.includes(item)) : allowed.includes(String(value));
    });
}

