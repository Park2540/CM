import type { PlanTaskTemplate, TaskCondition } from './construction-plan.template.js';

interface Row {
    code: string;
    name: string;
    team?: string;
    days?: number;
    when?: TaskCondition;
    note?: string;
    /** ทางเลือก (เงื่อนไขไม่ซ้อนกัน) ใช้ช่วงเวลาเดียวกับงานก่อนหน้า */
    alt?: boolean;
}

const DAY_MS = 86_400_000;
const toDay = (iso: string) => Date.parse(`${iso}T00:00:00Z`) / DAY_MS;
const fromDay = (day: number) => new Date(day * DAY_MS).toISOString().slice(0, 10);

/** น้ำหนักงาน (วัน) โดยประมาณจากชนิดงาน */
function weightOf(name: string): number {
    if (/\((Milestone|Hold Point)/.test(name)) return 0.5;
    if (/^บ่ม/.test(name)) return 3;
    if (/^(ออกแบบ|จัดทำแบบ|ติดตั้ง|ก่อ|ฉาบ|ร้อย|เดิน|งานตอก|งานเจาะ|ขุด|งานขุด|ถม|งานถม)/.test(name)) return 3;
    if (/^(ตรวจสอบ|ทดสอบ|เท|ถอดแบบ)/.test(name)) return 1;
    return 1.5;
}

/** งานเรียงต่อกันในช่วง start–end (รวมวันแรกและวันสุดท้าย) */
function sequence(start: string, end: string, team: string, rows: Row[]): PlanTaskTemplate[] {
    const slots: Row[][] = [];
    for (const row of rows) {
        if (row.alt && slots.length) slots[slots.length - 1]!.push(row);
        else slots.push([row]);
    }
    const weights = slots.map((slot) => Math.max(...slot.map((row) => row.days ?? weightOf(row.name))));
    const total = weights.reduce((sum, w) => sum + w, 0) || 1;
    const first = toDay(start);
    const span = toDay(end) - first + 1;
    let acc = 0;
    return slots.flatMap((slot, i) => {
        const from = first + Math.floor((acc / total) * span);
        acc += weights[i]!;
        const to = Math.max(from, first + Math.ceil((acc / total) * span) - 1);
        return slot.map((row): PlanTaskTemplate => ({
            code: row.code,
            name: row.name,
            team: row.team ?? team,
            start: /\(Milestone/.test(row.name) ? fromDay(to) : fromDay(from),
            end: fromDay(to),
            ...(row.note ? { note: row.note } : {}),
            ...(row.when ? { when: row.when } : {})
        }));
    });
}

/** รหัสต่อเนื่องของขั้นตอน (เช่น 05.01, 05.02, …) */
function counter(phase: string, from = 1) {
    let n = from - 1;
    return () => `${phase}.${String(++n).padStart(2, '0')}`;
}

